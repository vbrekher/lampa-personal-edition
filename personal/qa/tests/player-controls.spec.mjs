import {test,expect} from '@playwright/test';
import {readLanguage} from '../../../tools/i18n-audit.mjs';
for(const locale of ['nl','en','ar','ur','he'])test(`${locale} real video remote pause, seek and quality selection`,async({page})=>{
 test.setTimeout(90000);
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.route('**/*',route=>new URL(route.request().url()).hostname==='127.0.0.1'||route.request().url().startsWith('data:')?route.continue():route.abort());
 await page.goto(`/?locale=${locale}&screen=player`);
 await expect(page.locator('body')).toHaveAttribute('data-qa-ready','player');
 const video=page.locator('video').first();
 await expect.poll(()=>video.evaluate(v=>v.currentTime)).toBeGreaterThan(0.5);
 await page.keyboard.press('Enter',{delay:120});
 await expect.poll(()=>video.evaluate(v=>v.paused)).toBe(true);
 await page.keyboard.press('Enter',{delay:120});
 await expect.poll(()=>video.evaluate(v=>v.paused)).toBe(false);
 const before=await video.evaluate(v=>v.currentTime);
 await page.keyboard.press('ArrowRight',{delay:120});
 await expect.poll(()=>video.evaluate(v=>v.currentTime)).toBeGreaterThan(before+3);
 await page.keyboard.press('ArrowUp',{delay:120});
 await expect(page.locator('.player-panel__playpause')).toHaveClass(/focus/);
 for(let n=0;n<8&&!await page.locator('.player-panel__quality').evaluate(e=>e.classList.contains('focus'));n++)await page.keyboard.press(['ar','ur','he'].includes(locale)?'ArrowLeft':'ArrowRight',{delay:120});
 await expect(page.locator('.player-panel__quality')).toHaveClass(/focus/);
 const original=await video.getAttribute('src');
 await page.keyboard.press('Enter',{delay:120});
 await expect(page.locator('.selectbox__title')).toContainText(readLanguage(locale).player_quality);
 const options=(await page.locator('.selectbox-item').allTextContents()).map(x=>x.trim());
 const chosen=original.includes('fixture-720')?'360p':'720p';
 const focused=(await page.locator('.selectbox-item.focus').innerText()).trim();
 const delta=options.findIndex(x=>x.includes(chosen))-options.findIndex(x=>x===focused);
 for(let n=0;n<Math.abs(delta);n++)await page.keyboard.press(delta>0?'ArrowDown':'ArrowUp',{delay:120});
 await expect(page.locator('.selectbox-item.focus')).toContainText(chosen);
 await page.keyboard.press('Enter',{delay:120});
 await expect(video).toHaveAttribute('src',new RegExp(chosen==='720p'?'fixture-720\\.mp4':'/fixture\\.mp4'));
 await expect.poll(()=>video.evaluate(v=>v.readyState)).toBeGreaterThanOrEqual(2);
 expect(errors).toEqual([]);
});
